# 4. RECONNECTION & SEQUENCE INTEGRITY
# =====================================================================
def test_e2e_reconnection_and_sequence(socket_client):
    """
    Tests socket client reconnect handshake and room re-attachment.
    """
    # 1. Ping
    socket_client.emit("ping_server", {"seq": 1})
    pongs = [e for e in socket_client.get_received() if e["name"] == "pong_server"]
    assert pongs

    # 2. Reconnect ack
    socket_client.emit("reconnect_ack", {"patient_id": 1})
    acks = [e for e in socket_client.get_received() if e["name"] == "reconnect_confirmed"]
    assert acks
    assert acks[0]["args"][0]["patient_id"] == 1
