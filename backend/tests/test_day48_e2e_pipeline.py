# 1. COMPLETE PIPELINE: SIMULATOR -> INGESTION -> DB -> ALERTS
# =====================================================================
def test_e2e_full_pipeline_flow(app, socket_client):
    """
    Test full telemetry pipeline for a single patient with acute arrhythmia.
    Verifies: simulation -> ingestion -> database storage -> alert engine.
    """
    with app.app_context():
        patient = Patient.query.first()
        assert patient is not None, "Need at least one patient"
        pid = patient.id

        # 1. Simulator generates reading
        raw_reading = PatientTelemetrySimulator.generate_reading(patient_id=pid, scenario="arrhythmia_tachycardia")
        assert raw_reading["heart_rate"] >= 120

        # 2. Join Socket room
        socket_client.emit("join_patient_room", {"patient_id": pid})
        received = socket_client.get_received()
        assert any(e["name"] == "room_joined" for e in received)

        # 3. Ingest through pipeline
        success, msg, vital_dict = IngestionPipeline.ingest_reading(raw_reading)
        assert success is True
        assert vital_dict["patient_id"] == pid
        assert vital_dict["data_quality"] == "valid"

        # 4. Verify DB persistence
        stored_vital = VitalObservation.query.filter_by(patient_id=pid).order_by(VitalObservation.id.desc()).first()
        assert stored_vital is not None
        assert float(stored_vital.heart_rate) == vital_dict["heart_rate"]

        # 5. Verify alert generated by engine
        alert = Alert.query.filter_by(patient_id=pid, alert_type="HR_ALERT").order_by(Alert.id.desc()).first()
        assert alert is not None
        assert alert.severity in ("WARNING", "CRITICAL")
        assert "DEMO" in alert.description


