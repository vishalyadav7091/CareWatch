# 2. MULTI-BED INDEPENDENCE (10+ SIMULATED BEDS)
# =====================================================================
def test_e2e_multi_bed_isolation(app):
    """
    Test 10 simulated ICU beds streaming telemetry independently.
    Verifies data from bed A never leaks into bed B.
    """
    with app.app_context():
        # Ensure 10 mock patients exist in test DB
        patients = []
        for i in range(1, 11):
            pcode = f"PAT-E2E-{i:03d}"
            p = Patient.query.filter_by(patient_code=pcode).first()
            if not p:
                p = Patient(
                    patient_code=pcode,
                    first_name=f"Patient{i}",
                    last_name="TestBed",
                    date_of_birth=datetime(1970 + i, 1, 1).date(),
                    gender="male" if i % 2 == 0 else "female",
                    created_at=datetime.now(timezone.utc),
                )
                db.session.add(p)
                db.session.commit()
            patients.append(p)

        # Simulate readings across all 10 beds with different clinical scenarios
        scenarios = ["stable", "arrhythmia_tachycardia", "desaturation_hypoxia", "septic_shock"]
        ingested_readings = {}
        for idx, p in enumerate(patients):
            sc = scenarios[idx % len(scenarios)]
            reading = PatientTelemetrySimulator.generate_reading(patient_id=p.id, scenario=sc)
            success, _, vital = IngestionPipeline.ingest_reading(reading)
            assert success is True
            ingested_readings[p.id] = (sc, vital)

        # Verify isolation: each patient's stored vital belongs strictly to them
        for pid, (sc, vital) in ingested_readings.items():
            db_vital = VitalObservation.query.filter_by(patient_id=pid).order_by(VitalObservation.id.desc()).first()
            assert db_vital.patient_id == pid
            assert float(db_vital.heart_rate) == vital["heart_rate"]
            assert float(db_vital.spo2) == vital["spo2"]


