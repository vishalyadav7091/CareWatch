# 3. AI/ML MODEL INFERENCE ON INGESTED VITALS
# =====================================================================
def test_e2e_ml_inference_on_ingested_vitals(app):
    """
    Verifies that a patient with accumulated vitals can run inference
    and return an experimental risk score with metadata.
    """
    with app.app_context():
        patient = Patient.query.first()
        pid = patient.id

        # Accumulate a 10-reading window
        for _ in range(10):
            r = PatientTelemetrySimulator.generate_reading(patient_id=pid, scenario="stable")
            IngestionPipeline.ingest_reading(r)

        # Ensure model is trained
        model = load_model()
        if model is None:
            train_and_save()
            model = load_model()
        assert model is not None

        # Fetch vitals window
        vitals = (
            VitalObservation.query.filter_by(patient_id=pid)
            .order_by(VitalObservation.measured_at.asc())
            .limit(10)
            .all()
        )
        window = [v.to_dict() for v in vitals]
        feats = extract_features(window).reshape(1, -1)
        prob = float(model.predict_proba(feats)[0][1])
        score = round(prob * 100, 1)

        assert 0.0 <= score <= 100.0


